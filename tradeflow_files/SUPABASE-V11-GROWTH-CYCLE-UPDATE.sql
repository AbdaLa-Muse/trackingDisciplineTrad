-- Compatibility wrapper: any old internal call now uses the v11 growth-cycle engine.
-- ============================================================
-- V11.1 REPAIR: FIRST-SIZE RESET CREATED AFTER EXISTING RETURN HISTORY
--
-- The original v11 could create the first reset on the day Account Size was set,
-- which hid earlier edited Trade Return % records. If an account has exactly one
-- reset and return history exists before it, move that initial reset back to the
-- earliest return date. Explicit later resets are preserved because accounts with
-- multiple reset events are not changed here.
-- ============================================================

with repair as (
  select
    rr.account_id,
    min(ar.review_date) as first_return_date,
    count(distinct rr.id) as reset_count,
    min(rr.id) as reset_id,
    min(rr.reset_date) as reset_date
  from public.tradeflow_account_resets rr
  join public.daily_review_account_risks ar
    on ar.account_id = rr.account_id
   and ar.trade_return_pct is not null
  group by rr.account_id
), eligible as (
  select *
  from repair
  where reset_count = 1
    and first_return_date < reset_date
)
update public.tradeflow_account_resets rr
set reset_date = e.first_return_date
from eligible e
where rr.id = e.reset_id;

